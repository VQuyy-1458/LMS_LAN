const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const events=new Map();
const window={cssEscape:value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))};
vm.runInNewContext(fs.readFileSync('static/js/list-controls.js','utf8'),{window,document:{addEventListener:(type,callback)=>events.set(type,callback)},Intl,Date,Map,Set,Promise,setTimeout,clearTimeout});
const ui=window.listUi,ids=rows=>Array.from(rows,r=>r.id||r.student_id);
const people=[{student_id:'SV10',full_name:'Bình',active:true},{student_id:'SV2',full_name:'Nguyễn An',active:false},{student_id:'SV1',full_name:'An',active:true}];
assert.deepEqual(ids(ui.view('admin:accounts',people,'people')),['SV1','SV2','SV10']);
ui.state('admin:accounts').dir='desc';
assert.deepEqual(ids(ui.view('admin:accounts',people,'people')),['SV10','SV2','SV1']);
ui.state('admin:accounts').status='locked';
assert.deepEqual(ids(ui.view('admin:accounts',people,'people')),['SV2']);
ui.state('admin:accounts').q='nguyen';
assert.deepEqual(ids(ui.view('admin:accounts',people,'people')),['SV2']);
const accountControls=ui.controls('admin:accounts');
assert(accountControls.includes('data-list-direction'));
assert(!accountControls.includes('data-list-sort'));
assert(!accountControls.includes('value="AC"'));
assert(!accountControls.includes('Loại file'));
const lockedAccounts=[{student_id:'A',active:true,login_locked:true},{student_id:'B',active:false,login_locked:true},{student_id:'C',active:true,login_locked:false}];
const savedAccountState={...ui.state('admin:accounts')};
Object.assign(ui.state('admin:accounts'),{q:'',status:'login_locked',dir:'asc'});
assert.deepEqual(ids(ui.view('admin:accounts',lockedAccounts,'people')),['A','B']);
ui.state('admin:accounts').status='login_ok';
assert.deepEqual(ids(ui.view('admin:accounts',lockedAccounts,'people')),['C']);
Object.assign(ui.state('admin:accounts'),savedAccountState);
assert.deepEqual(people.map(r=>r.student_id),['SV10','SV2','SV1']);

